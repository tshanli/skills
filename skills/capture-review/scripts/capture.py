#!/usr/bin/env python3
"""capture-review ledger tool: every deterministic step of the review-memory loop.

The rules file .agents/rules/code-review-rules.md is generated from the ledger
and owned entirely by this script; it is rewritten on every apply/render/reject.

Commands:
  list            print a compact ledger listing for the model to match against
  apply           read the model's decisions as JSON on stdin, record occurrences, promote due entries
  render          promote due entries and regenerate the rules file
  reject <id>     reject a rule: drop it from the rules file and never promote it again
  skip            record nothing (no reusable findings) but still run the Claude Code import check
  check           only run the Claude Code import check

Antigravity loads .agents/rules/*.md natively. Claude Code only sees the rules file
through @-imports (CLAUDE.md -> @AGENTS.md -> @.agents/rules/code-review-rules.md).
Every command that prints a summary checks that chain and appends a NOTE if it is broken.
It never edits CLAUDE.md or AGENTS.md. Set CAPTURE_CC_CHECK=0 to disable the check.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
from datetime import date

RULES_HEADER = """---
trigger: always_on
---

# Code Review Rules

<!-- Generated by capture.py from .agents/review-memory.jsonl. Do not edit by hand; use `capture.py reject <id>`. -->
"""
THRESHOLD = int(os.environ.get("CAPTURE_THRESHOLD", "2"))
CC_CHECK = os.environ.get("CAPTURE_CC_CHECK", "1") != "0"
IMPORT_DEPTH = 4  # Claude Code follows @-imports up to four hops
RULES_REL = ".agents/rules/code-review-rules.md"
AXES = {"standards", "adversarial"}
ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def fail(msg, code=1):
    print(f"[Review Memory] ERROR: {msg}")
    sys.exit(code)


def git(*args):
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        fail("not inside a git repository")


def paths():
    root = git("rev-parse", "--show-toplevel")
    return (root, os.path.join(root, ".agents", "review-memory.jsonl"),
            os.path.join(root, RULES_REL))


def bare_imports(path):
    """@-imports Claude Code would follow: outside fenced code blocks and inline code spans."""
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return []
    out, fence = [], None
    for line in text.splitlines():
        m = re.match(r"^\s*(`{3,}|~{3,})", line)
        if m:
            mark = m.group(1)[0] * 3
            if fence is None:
                fence = mark
            elif mark == fence:
                fence = None
            continue
        if fence:
            continue
        line = re.sub(r"`[^`]*`", "", line)
        out += re.findall(r"(?:^|\s)@([^\s`]+)", line)
    return out


def resolve(importer, target):
    base = os.path.dirname(os.path.realpath(importer))
    target = os.path.expanduser(target)
    return os.path.realpath(os.path.join(base, target))


def cc_note(root):
    """Return None if Claude Code reaches the rules file through imports, else a NOTE."""
    if not CC_CHECK:
        return None
    rules = os.path.realpath(os.path.join(root, RULES_REL))
    agents = os.path.realpath(os.path.join(root, "AGENTS.md"))
    starts = [os.path.join(root, n) for n in ("CLAUDE.md", ".claude/CLAUDE.md", "CLAUDE.local.md")]
    seen, frontier = set(), [os.path.realpath(p) for p in starts if os.path.exists(p)]
    seen.update(frontier)
    for _ in range(IMPORT_DEPTH):
        nxt = []
        for f in frontier:
            for t in bare_imports(f):
                r = resolve(f, t)
                if r == rules:  # may not exist yet: the first apply creates it
                    return None
                if r not in seen and os.path.isfile(r):
                    seen.add(r)
                    nxt.append(r)
        frontier = nxt
    if rules in seen:
        return None
    agents_ok = any(resolve(agents, t) == rules for t in bare_imports(agents))
    claude_ok = agents in seen
    missing = []
    if not claude_ok:
        missing.append('"@AGENTS.md" to CLAUDE.md (in .claude/CLAUDE.md use "@../AGENTS.md")')
    if not agents_ok:
        missing.append(f'"@{RULES_REL}" to AGENTS.md (bare line, not in backticks)')
    if not missing:  # both lines exist but the chain still does not resolve
        return "NOTE: Claude Code cannot reach the rules file; check the @-import paths"
    return "NOTE: Claude Code won't load the rules; add " + " and ".join(missing)


def with_note(line, root):
    note = cc_note(root)
    return f"{line}; {note}" if note else line


def load(ledger):
    if not os.path.exists(ledger):
        return []
    entries = []
    with open(ledger, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                entries.append(json.loads(line))
            except json.JSONDecodeError as e:
                fail(f"ledger line {n} is not valid JSON ({e}); nothing was changed")
    return entries


def atomic_write(path, text):
    path = os.path.realpath(path)  # write through symlinks instead of replacing them
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".tmp-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def save(ledger, entries):
    atomic_write(ledger, "".join(json.dumps(e, ensure_ascii=False) + "\n"
                                 for e in entries))


def promote_and_render(entries, rules):
    """Mark due entries as promoted, then rewrite the rules file. Return promoted ids."""
    due = [e for e in entries
           if e["status"] == "tracking" and e["count"] >= THRESHOLD]
    for e in due:
        e["status"] = "promoted"
    lines = [f"{e['rule']} <!-- {e['id']} -->" for e in entries
             if e["status"] == "promoted"]
    body = "\n".join(lines) + "\n" if lines else "_No rules promoted yet._\n"
    atomic_write(rules, RULES_HEADER + "\n" + body)
    return [e["id"] for e in due]


def cmd_list(entries):
    if not entries:
        print("(ledger is empty)")
        return
    for e in entries:
        print(f"{e['id']}\t{e['axis']}\t{e['status']}\t{e['count']}\t{e['pattern']}")


def cmd_apply(root, entries, ledger, rules):
    try:
        data = json.load(sys.stdin)
        findings = data["findings"]
        assert isinstance(findings, list)
    except Exception:
        fail('input must be JSON of the form {"findings": [...]}; nothing was changed')

    by_id = {e["id"]: e for e in entries}
    branch = git("rev-parse", "--abbrev-ref", "HEAD")
    commit = git("rev-parse", "--short", "HEAD")
    today = date.today().isoformat()

    # validate the whole batch first; reject it entirely on any error so nothing is half-written
    known = set(by_id)  # includes ids created earlier in this batch
    for i, f in enumerate(findings, 1):
        if not isinstance(f, dict):
            fail(f"finding {i} is not a JSON object")
        f["axis"] = axis = str(f.get("axis", "")).strip().lower()
        if axis not in AXES | {"spec"}:
            fail(f"finding {i}: axis must be standards or adversarial, got {axis!r}")
        if axis == "spec":
            continue
        match = f.get("match")
        if match is not None and match not in known:
            fail(f"finding {i}: match={match!r} is not in the ledger; use an existing id for a known pattern, or null for a new one")
        if match is None:
            fid = f.get("id", "")
            if not ID_RE.match(fid):
                fail(f"finding {i}: id {fid!r} is not kebab-case")
            if fid not in known:
                rule = str(f.get("rule", ""))
                if not f.get("pattern") or not rule.startswith("- "):
                    fail(f"finding {i} is new: it needs a pattern, and a rule starting with '- '")
                if "\n" in rule or "-->" in rule:
                    fail(f"finding {i}: rule must be a single line without '-->'")
                known.add(fid)

    added = bumped = dup = skipped = 0
    for f in findings:
        if f["axis"] == "spec":
            skipped += 1
            continue
        fid = f.get("match") or f["id"]
        file = (f.get("file") or "?").strip()
        key = f"{branch}|{file}"
        e = by_id.get(fid)
        if e is None:
            e = {"id": fid, "axis": f["axis"], "pattern": f["pattern"].strip(),
                 "rule": f["rule"].strip(), "status": "tracking", "count": 0,
                 "occurrences": [], "first_seen": today, "last_seen": today}
            entries.append(e)
            by_id[fid] = e
            added += 1
        elif any(o["key"] == key for o in e["occurrences"]):
            dup += 1  # same branch and file reviewed again: not counted
            continue
        else:
            bumped += 1
        e["occurrences"].append({"key": key, "branch": branch, "file": file,
                                 "commit": commit, "date": today})
        e["count"] = len(e["occurrences"])
        e["last_seen"] = today

    promoted = promote_and_render(entries, rules)
    save(ledger, entries)
    line = f"[Review Memory] new {added}, incremented {bumped}, duplicate {dup}, promoted {len(promoted)}"
    if promoted:
        line += f" ({', '.join(promoted)}; review with git diff .agents/rules/)"
    if skipped:
        line += f"; dropped {skipped} Spec"
    print(with_note(line, root))


def cmd_render(root, entries, ledger, rules):
    promoted = promote_and_render(entries, rules)
    save(ledger, entries)
    line = (f"[Review Memory] rendered {RULES_REL}; promoted {len(promoted)}" +
            (f" ({', '.join(promoted)})" if promoted else ""))
    print(with_note(line, root))


def cmd_reject(entries, ledger, rules, rid):
    e = next((x for x in entries if x["id"] == rid), None)
    if e is None:
        fail(f"{rid} is not in the ledger")
    e["status"] = "rejected"
    promote_and_render(entries, rules)
    save(ledger, entries)
    print(f"[Review Memory] rejected {rid}")


def main():
    if len(sys.argv) < 2:
        fail("usage: capture.py list | apply | render | reject <id> | skip | check")
    root, ledger, rules = paths()
    entries = load(ledger)
    cmd = sys.argv[1]
    if cmd == "list":
        cmd_list(entries)
    elif cmd == "apply":
        cmd_apply(root, entries, ledger, rules)
    elif cmd == "render":
        cmd_render(root, entries, ledger, rules)
    elif cmd == "skip":
        print(with_note("[Review Memory] nothing to record", root))
    elif cmd == "check":
        print(with_note("[Review Memory] Claude Code import check", root)
              if cc_note(root) else "[Review Memory] Claude Code import chain OK")
    elif cmd == "reject" and len(sys.argv) == 3:
        cmd_reject(entries, ledger, rules, sys.argv[2])
    else:
        fail(f"unknown command: {' '.join(sys.argv[1:])}")


if __name__ == "__main__":
    main()
