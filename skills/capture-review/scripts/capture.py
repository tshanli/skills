#!/usr/bin/env python3

"""capture-review ledger tool: every deterministic step of the review-memory loop.

The rules file .agents/rules/code-review-rules.md is generated from the ledger
and owned entirely by this script; it is rewritten on every apply/render/reject.

Commands:
  list            print a compact ledger listing for the model to match against
  apply           read the model's decisions as JSON on stdin, record occurrences, promote due entries
  render          promote due entries and regenerate the rules file (also creates it on first setup)
  reject <id>     reject a rule: drop it from the rules file and never promote it again
"""

import json
import os
import re
import subprocess
import sys
import tempfile
from datetime import date

RULES_HEADER = """---
trigger: always_on
---

# Code Review Rules

<!-- Generated by capture.py from .agents/review-memory.jsonl. Do not edit by hand; use `capture.py reject <id>`. -->
"""
THRESHOLD = int(os.environ.get("CAPTURE_THRESHOLD", "2"))
AXES = {"standards", "adversarial"}
ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def fail(msg, code=1):
    print(f"[Review Memory] ERROR: {msg}")
    sys.exit(code)


def git(*args):
    try:
        return subprocess.run(
            ["git", *args], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        fail("not inside a git repository")


def paths():
    root = git("rev-parse", "--show-toplevel")
    return (
        os.path.join(root, ".agents", "review-memory.jsonl"),
        os.path.join(root, ".agents", "rules", "code-review-rules.md"),
    )


def load(ledger):
    if not os.path.exists(ledger):
        return []
    entries = []
    with open(ledger, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                entries.append(json.loads(line))
            except json.JSONDecodeError as e:
                fail(f"ledger line {n} is not valid JSON ({e}); nothing was changed")
    return entries


def atomic_write(path, text):
    path = os.path.realpath(path)  # write through symlinks instead of replacing them
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".tmp-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def save(ledger, entries):
    atomic_write(
        ledger, "".join(json.dumps(e, ensure_ascii=False) + "\n" for e in entries)
    )


def promote_and_render(entries, rules):
    """Mark due entries as promoted, then rewrite the rules file. Return promoted ids."""
    due = [e for e in entries if e["status"] == "tracking" and e["count"] >= THRESHOLD]
    for e in due:
        e["status"] = "promoted"
    lines = [
        f"{e['rule']} <!-- {e['id']} -->" for e in entries if e["status"] == "promoted"
    ]
    body = "\n".join(lines) + "\n" if lines else "_No rules promoted yet._\n"
    atomic_write(rules, RULES_HEADER + "\n" + body)
    return [e["id"] for e in due]


def cmd_list(entries):
    if not entries:
        print("(ledger is empty)")
        return
    for e in entries:
        print(f"{e['id']}\t{e['axis']}\t{e['status']}\t{e['count']}\t{e['pattern']}")


def cmd_apply(entries, ledger, rules):
    try:
        data = json.load(sys.stdin)
        findings = data["findings"]
        assert isinstance(findings, list)
    except Exception:
        fail('input must be JSON of the form {"findings": [...]}; nothing was changed')

    by_id = {e["id"]: e for e in entries}
    branch = git("rev-parse", "--abbrev-ref", "HEAD")
    commit = git("rev-parse", "--short", "HEAD")
    today = date.today().isoformat()

    # validate the whole batch first; reject it entirely on any error so nothing is half-written
    known = set(by_id)  # includes ids created earlier in this batch
    for i, f in enumerate(findings, 1):
        if not isinstance(f, dict):
            fail(f"finding {i} is not a JSON object")
        f["axis"] = axis = str(f.get("axis", "")).strip().lower()
        if axis not in AXES | {"spec"}:
            fail(f"finding {i}: axis must be standards or adversarial, got {axis!r}")
        if axis == "spec":
            continue
        match = f.get("match")
        if match is not None and match not in known:
            fail(
                f"finding {i}: match={match!r} is not in the ledger; use an existing id for a known pattern, or null for a new one"
            )
        if match is None:
            fid = f.get("id", "")
            if not ID_RE.match(fid):
                fail(f"finding {i}: id {fid!r} is not kebab-case")
            if fid not in known:
                rule = str(f.get("rule", ""))
                if not f.get("pattern") or not rule.startswith("- "):
                    fail(
                        f"finding {i} is new: it needs a pattern, and a rule starting with '- '"
                    )
                if "\n" in rule or "-->" in rule:
                    fail(f"finding {i}: rule must be a single line without '-->'")
                known.add(fid)

    added = bumped = dup = skipped = 0
    for f in findings:
        if f["axis"] == "spec":
            skipped += 1
            continue
        fid = f.get("match") or f["id"]
        file = (f.get("file") or "?").strip()
        key = f"{branch}|{file}"
        e = by_id.get(fid)
        if e is None:
            e = {
                "id": fid,
                "axis": f["axis"],
                "pattern": f["pattern"].strip(),
                "rule": f["rule"].strip(),
                "status": "tracking",
                "count": 0,
                "occurrences": [],
                "first_seen": today,
                "last_seen": today,
            }
            entries.append(e)
            by_id[fid] = e
            added += 1
        elif any(o["key"] == key for o in e["occurrences"]):
            dup += 1  # same branch and file reviewed again: not counted
            continue
        else:
            bumped += 1
        e["occurrences"].append(
            {
                "key": key,
                "branch": branch,
                "file": file,
                "commit": commit,
                "date": today,
            }
        )
        e["count"] = len(e["occurrences"])
        e["last_seen"] = today

    promoted = promote_and_render(entries, rules)
    save(ledger, entries)
    line = f"[Review Memory] new {added}, incremented {bumped}, duplicate {dup}, promoted {len(promoted)}"
    if promoted:
        line += f" ({', '.join(promoted)}; review with git diff .agents/rules/)"
    if skipped:
        line += f"; dropped {skipped} Spec"
    print(line)


def cmd_render(entries, ledger, rules):
    promoted = promote_and_render(entries, rules)
    save(ledger, entries)
    print(
        f"[Review Memory] rendered {os.path.relpath(rules)}; promoted {len(promoted)}"
        + (f" ({', '.join(promoted)})" if promoted else "")
    )


def cmd_reject(entries, ledger, rules, rid):
    e = next((x for x in entries if x["id"] == rid), None)
    if e is None:
        fail(f"{rid} is not in the ledger")
    e["status"] = "rejected"
    promote_and_render(entries, rules)
    save(ledger, entries)
    print(f"[Review Memory] rejected {rid}")


def main():
    if len(sys.argv) < 2:
        fail("usage: capture.py list | apply | render | reject <id>")
    ledger, rules = paths()
    entries = load(ledger)
    cmd = sys.argv[1]
    if cmd == "list":
        cmd_list(entries)
    elif cmd == "apply":
        cmd_apply(entries, ledger, rules)
    elif cmd == "render":
        cmd_render(entries, ledger, rules)
    elif cmd == "reject" and len(sys.argv) == 3:
        cmd_reject(entries, ledger, rules, sys.argv[2])
    else:
        fail(f"unknown command: {' '.join(sys.argv[1:])}")


if __name__ == "__main__":
    main()
